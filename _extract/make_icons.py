"""Build the bundled Material Symbols subset used by the app.

Run once from the repo root:  python _extract/make_icons.py
It reads the downloaded variable font + codepoints list and writes
assets/icons.ttf (outlined) and assets/icons_filled.ttf (filled) plus
app/ui/icons.py with the name -> codepoint map.
"""
import os
import sys
from pathlib import Path

from fontTools import subset
from fontTools.varLib import instancer

NAMES = """
home download settings key favorite favorite_border album library_music queue_music
playlist_play play_arrow stop_circle pause_circle refresh restart_alt sync check
check_circle error warning info hourglass_empty task_alt cancel close search add
remove expand_more expand_less chevron_right arrow_back arrow_forward more_vert link
content_paste folder_open person visibility visibility_off delete select_all deselect
tune speed music_note open_in_new save edit cloud_download download_done pending
signal_cellular_alt bolt verified headphones audiotrack subtitles image
format_list_bulleted dashboard playlist_add_check key_off system_update update history
list done_all indeterminate_check_box radio_button_unchecked radio_button_checked
logout login account_circle graphic_eq lyrics shield_lock sort filter_alt
""".split()

SRC = Path(os.environ["TEMP"]) / "msr.ttf"
CP = Path(os.environ["TEMP"]) / "msr.codepoints"
OUT = Path(__file__).resolve().parent.parent / "assets"
PY = Path(__file__).resolve().parent.parent / "app" / "ui" / "icons.py"


def main() -> int:
    mapping = {}
    for line in CP.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2:
            mapping[parts[0]] = parts[1]

    chosen = {}
    for name in NAMES:
        if name not in mapping:
            print(f"missing icon: {name}")
            continue
        chosen[name] = int(mapping[name], 16)

    unicodes = sorted(set(chosen.values()))
    OUT.mkdir(parents=True, exist_ok=True)

    base = _load(SRC)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.recalc_bounds = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(base)
    slim = Path(__file__).resolve().parent / "msr_slim.ttf"
    base.save(slim)

    for suffix, axes in (("", {"FILL": 0}), ("_filled", {"FILL": 1})):
        font = instancer.instantiateVariableFont(
            _load(slim), {"wght": 400, "opsz": 24, **axes}, inplace=True
        )
        target = OUT / f"icons{suffix}.ttf"
        font.save(target)
        print(f"{target.name}: {target.stat().st_size} bytes")

    lines = [
        '"""Auto-generated by _extract/make_icons.py — Material Symbols codepoints."""',
        "",
        "ICONS = {",
    ]
    for name, cp in chosen.items():
        lines.append(f'    "{name}": "\\u{cp:04x}",')
    lines.append("}")
    PY.parent.mkdir(parents=True, exist_ok=True)
    PY.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{PY}: {len(chosen)} icons")
    return 0


def _load(path: Path):
    from fontTools.ttLib import TTFont

    return TTFont(path)


if __name__ == "__main__":
    sys.exit(main())
