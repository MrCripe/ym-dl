const DICTS: Record<Lang, Dict> = { ru, en };

/** Picks the language to use: an explicit choice wins, `auto` follows the system. */
export function resolveLang(pref: string | undefined): Lang {
  if (pref === "ru" || pref === "en") return pref;
  const system =
    typeof navigator !== "undefined" ? (navigator.language || "").toLowerCase() : "";
  return system.startsWith("ru") ? "ru" : "en";
}

/** Looks a key up, falling back to Russian and then to the key itself. */
export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const text = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

/**
 * The translator for the current interface language.
 *
 * Reads the settings draft rather than the saved settings so a language change is
 * visible the moment it is picked, like the theme and accent already are.
 */
export function useT() {
  const pref = useApp((state) => (state.settingsDraft ?? state.settings)?.language);
  const lang = resolveLang(pref);
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  );
}

/** The bare language, for the few places that need it without a lookup. */
export function useLang(): Lang {
  const pref = useApp((state) => (state.settingsDraft ?? state.settings)?.language);
  return resolveLang(pref);
}

