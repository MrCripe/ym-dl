"""Writes the 1.4.0 changelog section at the top of CHANGELOG.md.

The file uses CRLF; a naive write with plain \\n silently mangles it, so the
line ending is detected and restored. Run from the repo root:

    python tools/write_changelog.py
"""

import io
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHANGELOG = ROOT / "CHANGELOG.md"

SECTION = """## 1.4.0

Это обновление убирает проводник и сторонний редактор тегов из работы с уже
скачанной музыкой. Раньше приложение умело только качать; теперь у него есть
своя библиотека, поиск по каталогу и очередь загрузок.

### Библиотека

Новый раздел со всем, что уже лежит на диске. Список строится из локального
реестра на SQLite, а не из обхода папки, поэтому открывается сразу.

- Сортировка по дате, исполнителю, альбому, году и названию, в обе стороны.
- Поиск по названию, исполнителю и альбому. Регистр не важен, кириллица тоже:
  «блэйд» находит «БЛЭЙД».
- Правка тегов прямо в окне. Изменения записываются в сам файл, а не только в
  базу: название, исполнитель, исполнитель альбома, альбом, жанр, год, номер
  трека.
- Обложка видна в каждой строке, клик по ней заменяет картинку в файле.
- Удаление трека убирает и файл, и запись в реестре. Если файл занят, строка
  остаётся: удалить можно попробовать снова.
- Кнопка повышения качества перекачивает трек в лучшем виде, если аккаунт его
  отдаёт, и заменяет файл на месте. Старый файл удаляется только после того, как
  новый записан и размечен.
- Прослушивание: трек играет из библиотеки, полоса прогресса работает как
  перемотка, плеер не сбрасывается при переходе между экранами.

### Поиск по каталогу

- Поиск по трекам, исполнителям, альбомам и плейлистам внутри приложения.
- Если запрос совпадает с именем исполнителя, вперёд идут его песни, а не одна
  карточка. Регистр и лишние пробелы не мешают.
- Результат разложен как в привычном клиенте: треки в две колонки, ниже полки
  исполнителей, альбомов и плейлистов. Обложки подгружаются сразу.

### Очередь загрузок

- Кнопка «В очередь» запоминает выбранное, но не начинает загрузку. Собрав всё
  нужное, нажмите «Начать»: файлы пойдут по порядку.
- Очередь показывает, что в ней лежит и сколько там треков.
- Неудачный запуск больше не стирает собранную очередь.
- Каждый источник помнит свой шаблон раскладки: «Мне нравится», альбом и
  одиночный трек в одной очереди раскладываются по-разному.

### Раскладка файлов

Шаблон пути больше не один на всё. Их три: для «Мне нравится», для альбомов и
для одиночных треков. В каждом можно выбрать готовый вариант с примером
результата или написать свой. Старый общий шаблон подхватывается при первом
запуске, ничего перенастраивать не нужно.

### Интерфейс

- Живой фон: акцентные пятна медленно переливаются за содержимым.
- Поля ввода приведены к одному виду: скруглённая рамка вместо залитой плашки с
  подчёркиванием.
- Анимации: переход между экранами, бегущая плашка в переключателях, появление
  групп раскладки и результатов поиска.
- Экран загрузок больше не дёргается на каждой строке журнала.

### Исправления

- Поле ввода в модальном окне и плеер были прозрачными: использовался цвет,
  которого нет в теме.
- Замена обложки не срабатывала: новая картинка дописывалась второй, а
  показывалась первая. Файл при этом рос на размер обложки при каждом
  сохранении.
- «Открыть папку» на экране загрузок падало с ошибкой `0xc0000142` вместо того,
  чтобы открыть проводник.
- Поиск по каталогу не находил ничего: ответ сервиса разбирался как будто у него
  есть обёртка `result`, которой там нет.
- Ссылка на исполнителя могла уйти в бесконечный цикл запросов, если сервис не
  присылал размер страницы.
- Повышение качества на файл с расширением в верхнем регистре (`Song.FLAC`) могло
  удалить только что записанный файл.
- Повышение качества больше не перезаписывает оригинал до того, как новый файл
  размечен: при сбое старый трек остаётся на месте.
- Плеер при переходе в библиотеку больше не включает трек сам.
- Приложение больше не подлагивает при открытии библиотеки: чтение обложек и
  сканирование папки ушли с потока окна, схема базы создаётся один раз, а не на
  каждом запросе.

### Прочее

- Убраны разделы, которые дублировали системные возможности: описание папки
  загрузки, «Перепаковать папку», «Как установлена» в разделе о программе.
- «Заменить токен» переименовано в «Выйти из аккаунта».
- Плашка обновления стала одной строкой с кнопкой и не перекрывает плеер.
- README переписан, скриншоты собраны в едином оформлении.

"""


def main() -> None:
    raw = io.open(CHANGELOG, "rb").read()
    crlf = b"\r\n" in raw
    text = raw.decode("utf-8").replace("\r\n", "\n")
    marker = "## 1.3.4"
    if marker not in text:
        raise SystemExit("no 1.3.4 section to insert before")
    if "## 1.4.0" in text:
        raise SystemExit("1.4.0 section already present")
    text = text.replace(marker, SECTION + marker, 1)
    if crlf:
        text = text.replace("\n", "\r\n")
    io.open(CHANGELOG, "wb").write(text.encode("utf-8"))
    print("changelog updated", "crlf" if crlf else "lf")


if __name__ == "__main__":
    main()
